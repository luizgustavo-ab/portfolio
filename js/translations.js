/* Aplicação do idioma. Ignorado quando não há DOM. */
(() => {
  if (typeof document === "undefined") return;

  const strings = window.PortfolioStrings;
  const storageKey = "portfolioLanguage";
  const root = document.documentElement;

  function savedLanguage() {
    try {
      return localStorage.getItem(storageKey);
    } catch {
      return null;
    }
  }

  function applyLanguage(language) {
    const selected = strings[language] ? language : "pt";
    const dictionary = strings[selected];

    document.querySelectorAll("[data-i18n]").forEach((element) => {
      const text = dictionary[element.dataset.i18n];

      if (text) element.textContent = text;
    });

    // data-i18n-attr="atributo:chave;outro-atributo:outraChave"
    document.querySelectorAll("[data-i18n-attr]").forEach((element) => {
      element.dataset.i18nAttr.split(";").forEach((pair) => {
        const [attribute, key] = pair.split(":");

        if (dictionary[key]) element.setAttribute(attribute, dictionary[key]);
      });
    });

    document.querySelectorAll(".lang-btn").forEach((button) => {
      const active = button.dataset.lang === selected;

      button.classList.toggle("active", active);
      button.setAttribute("aria-pressed", String(active));
    });

    root.lang = selected === "pt" ? "pt-BR" : "en";
    root.classList.remove("i18n-pending");
  }

  function currentStrings() {
    return strings[root.lang === "en" ? "en" : "pt"];
  }

  document.querySelectorAll(".lang-btn").forEach((button) => {
    button.addEventListener("click", () => {
      applyLanguage(button.dataset.lang);

      try {
        localStorage.setItem(storageKey, button.dataset.lang);
      } catch {
        /* sem armazenamento: o idioma vale só nesta página */
      }
    });
  });

  // Voltar pelo histórico pode restaurar a página com o idioma antigo
  window.addEventListener("pageshow", (event) => {
    if (event.persisted) applyLanguage(savedLanguage() || "pt");
  });

  applyLanguage(savedLanguage() || "pt");

  window.Portfolio = { ...window.Portfolio, applyLanguage, currentStrings };
})();
